#!/usr/bin/env python3
"""Fails on a dangling res:// path or markdown link, a .gd without its .uid (or the reverse), a *_test.gd
missing from scripts/test.sh, and any res://view or res://app reference under sim/ (the layering rule)."""
import os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
tracked = subprocess.run(['git', 'ls-files'], capture_output=True, text=True, check=True).stdout.splitlines()
tracked = [p for p in tracked if os.path.exists(p)]
errors = []
tracked_set = set(tracked)
def exists_res(path):
    return os.path.exists(path) or os.path.exists(path + '.import')
text = [p for p in tracked if p.endswith(('.gd', '.tscn', '.cfg', '.md', '.sh', '.yml', '.godot')) and not p.startswith('docs/screenshots/')]
res = re.compile(r'res://([A-Za-z0-9_./-]+)')
for p in text:
    src = open(p, encoding='utf-8', errors='ignore').read()
    for m in res.finditer(src):
        target = m.group(1).rstrip('.')
        if target.startswith(('.godot/', 'content/audio/')) or '%' in target or target.endswith('/'): continue
        if target.startswith('docs/screenshots/') : continue
        if not exists_res(target) and not os.path.isdir(target):
            errors.append(f'{p}: dangling res://{target}')
    if p.endswith('.md'):
        for m in re.finditer(r'\]\(([^)#\s]+)(?:#[^)\s]*)?\)', src):
            target = m.group(1)
            if re.match(r'^(https?:|mailto:)', target): continue
            full = os.path.normpath(os.path.join(os.path.dirname(p), target))
            if not os.path.exists(full): errors.append(f'{p}: broken link {target}')
    if p.startswith('sim/') and p.endswith('.gd') and re.search(r'res://(view|app)/', src):
        errors.append(f'{p}: the simulation must not depend on view/ or app/')
for p in tracked:
    if re.search(r' \d+(\.|$)', os.path.basename(p)) and p.endswith(('.gd', '.uid', '.md', '.sh', '.py', '.tscn')):
        errors.append(f'{p}: looks like a stray sync/duplicate copy ("name 2.ext")')
for p in tracked:
    if p.endswith('.gd') and not p.startswith('tests/captures/') and (p + '.uid') not in tracked_set and os.path.exists(p + '.uid') is False:
        pass   # .uid files are regenerated by Godot; not required to be tracked
test_sh = open('scripts/test.sh', encoding='utf-8').read()
listed = set(re.findall(r'[\w/]+_test', test_sh))
allowed_unlisted = {'regional_test'}
for p in tracked:
    m = re.match(r'tests/((?:sim|view)/\w+_test)\.gd$', p)
    if m and m.group(1) not in listed and m.group(1).split('/')[1] not in allowed_unlisted:
        errors.append(f'{p}: not listed in scripts/test.sh')
if errors:
    print('\n'.join(errors)); sys.exit(1)
print('layout ok:', len(text), 'files checked')
